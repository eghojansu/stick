namespace Fal\Stick;

class Event
{
    protected $propagationStopped = false;

    public function isPropagationStopped()
    {
        return $this->propagationStopped;
    }

    public function stopPropagation()
    {
        $this->propagationStopped = true;

        return $this;
    }
}
